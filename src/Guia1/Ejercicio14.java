package Guia1;

/* Imprimir todos los numeros impares del 1 al 100 usando un ciclo while. */

public class Ejercicio14 {
    
    public void NumerosImparesWH(){

        int contador = 1;

        while (contador <= 100) {

            System.out.println("Número:" + contador );

            contador += 2;

        }
    }

}