package Guia1;

/* Calcular la suma de los numeros del 1 al 100 usando un ciclo for.
Basico */
public class Ejercicio15 {

     public void Suma1a100() {

        int Suma = 0;

        for (int i = 1; i <= 100 ; i++) {

            Suma += i;

        }

        System.out.println("La suma de estos números es de:" + Suma ); 



    } 

    
}
